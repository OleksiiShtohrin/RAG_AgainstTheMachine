"""Data models for search and answer results used in CLI and evaluation."""

from typing import List
from pydantic import BaseModel
from src.models.source import MinimalSource


class MinimalSearchResults(BaseModel):
    """Search result for a single question containing retrieved sources.

    Attributes:
        question_id: Identifier of the evaluated question.
        question: Text of the question.
        retrieved_sources: Top-k retrieved source citations.
    """

    question_id: str
    question: str
    retrieved_sources: List[MinimalSource]


class MinimalAnswer(MinimalSearchResults):
    """Answer result for a single question including LLM generated answer.

    Attributes:
        answer: Natural language response generated by the language model.
    """

    answer: str


class StudentSearchResults(BaseModel):
    """Batch output format for the search_dataset command.

    Attributes:
        search_results: Collection of search results for all questions.
        k: Number of retrieved candidate citations per question.
    """

    search_results: List[MinimalSearchResults]
    k: int


class StudentSearchResultsAndAnswer(BaseModel):
    """Batch output format for the answer_dataset command.

    Attributes:
        search_results: Collection of answer results with retrieved citations.
        k: Number of candidate citations requested per question.
    """

    search_results: List[MinimalAnswer]
    k: int
